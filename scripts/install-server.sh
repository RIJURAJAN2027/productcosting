#!/usr/bin/env bash
# One-step installation on a Linux server – e.g. a Hostinger VPS with the "Ubuntu 24.04 with Docker"
# template, or any Ubuntu/Debian server.
#
#   git clone https://github.com/RIJURAJAN2027/productcosting.git
#   cd productcosting
#   sudo scripts/install-server.sh
#
# It asks for a domain, the administrator's e-mail and the organisation name, writes .env with
# generated passwords and secrets (an existing .env is kept), starts PostgreSQL and the application
# with Docker and – with a domain – an HTTPS proxy with a free Let's Encrypt certificate, and can
# schedule a daily database backup. Run it again after `git pull` to upgrade.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

bold() { printf '\n\033[1m%s\033[0m\n' "$*"; }
rand() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1" || true; }
ask() { local reply; read -r -p "$1" reply || true; printf '%s' "$reply"; }
yes_no() { local reply; reply="$(ask "$1")"; reply="${reply:-$2}"; [[ "${reply,,}" == y* ]]; }

# ---------------------------------------------------------------- Docker
if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  bold "Docker with the Compose plugin is needed."
  if yes_no "Install it now with Docker's official script (get.docker.com)? [y/N] " n; then
    curl -fsSL https://get.docker.com | sh
  else
    echo "Install Docker first: https://docs.docker.com/engine/install/" >&2
    exit 1
  fi
fi

# ---------------------------------------------------------------- configuration (.env)
NEW_PASSWORD=""
if [[ -f .env ]]; then
  bold "Using the existing .env (move it away to configure from scratch)."
else
  bold "Configuration"
  DOMAIN="$(ask "Domain or subdomain for HTTPS, e.g. costing.example.com
  (its DNS A record must already point to this server; leave empty to use http on port 8080): ")"
  ADMIN_EMAIL="$(ask "Administrator e-mail: ")"
  ORG="$(ask "Organisation name: ")"
  DEMO=false
  if yes_no "Add the fictional demo company for training? [y/N] " n; then DEMO=true; fi
  NEW_PASSWORD="$(rand 8)Aa7$(rand 6)"
  {
    echo "# Generated by scripts/install-server.sh on $(date -u +%Y-%m-%d). Keep this file private."
    echo "POSTGRES_PASSWORD=$(rand 32)"
    echo "PC_SECRET_KEY=$(rand 64)"
    echo "PC_BOOTSTRAP_TENANT=\"${ORG:-My Organisation}\""
    echo "PC_BOOTSTRAP_ADMIN_EMAIL=\"${ADMIN_EMAIL:-admin@example.com}\""
    echo "PC_BOOTSTRAP_ADMIN_PASSWORD=${NEW_PASSWORD}"
    echo "PC_LOAD_DEMO_COMPANY=${DEMO}"
    echo "WEB_CONCURRENCY=2"
    if [[ -n "${DOMAIN}" ]]; then
      echo "DOMAIN=${DOMAIN}"
      echo "COMPOSE_PROFILES=https"
      echo "APP_BIND=127.0.0.1"
      echo "PC_OIDC_REDIRECT_URI=https://${DOMAIN}/api/auth/sso/callback"
    fi
  } > .env
  chmod 600 .env
fi
DOMAIN="$(grep -E '^DOMAIN=' .env | cut -d= -f2- | tr -d '"' || true)"

# ---------------------------------------------------------------- firewall (when ufw is active)
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  if [[ -n "${DOMAIN}" ]]; then ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw allow 443/udp >/dev/null
  else ufw allow 8080/tcp >/dev/null; fi
  echo "Firewall (ufw): web ports opened."
fi

# ---------------------------------------------------------------- build and start
# a CA certificate for a TLS-inspecting proxy must be inside this folder for docker compose
if [[ -n "${BUILD_CA_FILE:-}" && "$(realpath "${BUILD_CA_FILE}")" != "${ROOT}"/* ]]; then
  cp "${BUILD_CA_FILE}" docker/.build-ca.local.pem
  export BUILD_CA_FILE=./docker/.build-ca.local.pem
fi
bold "Building and starting (the first build takes a few minutes)…"
if [[ "${NO_BUILD:-0}" == 1 ]]; then docker compose up -d; else docker compose up -d --build; fi

bold "Waiting for the application…"
ready=0
for _ in $(seq 1 120); do
  if docker compose exec -T app python -c \
      "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/api/health', timeout=3)" \
      >/dev/null 2>&1; then ready=1; break; fi
  sleep 2
done
if [[ "${ready}" != 1 ]]; then
  echo "The application did not start. See: docker compose logs app" >&2
  exit 1
fi

# ---------------------------------------------------------------- daily backup
if command -v crontab >/dev/null 2>&1 && ! (crontab -l 2>/dev/null | grep -q "productcosting-backup"); then
  if yes_no "Schedule a daily database backup at 02:15 into ${ROOT}/backups (kept 30 days)? [Y/n] " y; then
    (crontab -l 2>/dev/null; echo "15 2 * * * cd ${ROOT} && scripts/backup-db.sh >/dev/null 2>&1 # productcosting-backup") | crontab -
    echo "Daily backup scheduled (copy the backups folder off the server regularly)."
  fi
fi

# ---------------------------------------------------------------- summary
if [[ -n "${DOMAIN}" ]]; then
  URL="https://${DOMAIN}"
else
  IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
  URL="http://${IP:-this-server}:8080   (no HTTPS – set up a domain before entering real data)"
fi
bold "Product Costing is running: ${URL}"
if [[ -n "${NEW_PASSWORD}" ]]; then
  echo "Sign in as $(grep -E '^PC_BOOTSTRAP_ADMIN_EMAIL=' .env | cut -d= -f2- | tr -d '"') with the password:"
  echo "    ${NEW_PASSWORD}"
  echo "Change it after the first sign-in (Profile). It is also stored in .env."
fi
echo "Upgrade later with:  git pull && sudo scripts/install-server.sh"
