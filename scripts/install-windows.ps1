<#
  Product Costing - install and start on a Windows PC or laptop.

  1. Install Docker Desktop (https://www.docker.com/products/docker-desktop/) and start it.
  2. Right-click this file > "Run with PowerShell"
     (or in PowerShell, in the product-costing folder:
      powershell -ExecutionPolicy Bypass -File scripts\install-windows.ps1)

  The first time it asks for the administrator's e-mail and the organisation name, creates .env with
  generated passwords (an existing .env is kept), builds and starts the application and its
  database, and opens http://localhost:8080 in the browser.
  Run it again to start the application after a restart, or to upgrade after getting a new version.
#>
$ErrorActionPreference = 'Continue'
Set-Location (Split-Path -Parent $PSScriptRoot)

function New-Secret([int]$Length) {
    $chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'.ToCharArray()
    $bytes = New-Object byte[] $Length
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

function Stop-WithMessage([string]$Message) {
    Write-Host ''
    Write-Host $Message -ForegroundColor Red
    Read-Host 'Press Enter to close'
    exit 1
}

# ------------------------------------------------------------------ Docker Desktop
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Stop-WithMessage 'Docker Desktop is not installed. Install it from https://www.docker.com/products/docker-desktop/, start it, then run this again.'
}
docker info *> $null
if ($LASTEXITCODE -ne 0) {
    Stop-WithMessage 'Docker Desktop is not running. Start it (whale icon), wait until it shows "Engine running", then run this again.'
}

# ------------------------------------------------------------------ configuration (.env)
$envFile = Join-Path (Get-Location) '.env'
$newPassword = $null
$email = $null
if (Test-Path $envFile) {
    Write-Host 'Using the existing .env file.'
} else {
    Write-Host 'First-time set-up' -ForegroundColor Cyan
    $email = (Read-Host 'Administrator e-mail').Trim()
    if (-not $email) { $email = 'admin@example.com' }
    $org = ((Read-Host 'Organisation name') -replace '[\"$]', '').Trim()
    if (-not $org) { $org = 'My Organisation' }
    $demo = Read-Host 'Add the fictional demo company for training? (y/N)'
    $demoValue = 'false'
    if ($demo -match '^[yY]') { $demoValue = 'true' }
    $newPassword = (New-Secret 8) + 'Aa7' + (New-Secret 6)
    $lines = @(
        "# Generated by scripts/install-windows.ps1 on $(Get-Date -Format yyyy-MM-dd). Keep this file private.",
        "POSTGRES_PASSWORD=$(New-Secret 32)",
        "PC_SECRET_KEY=$(New-Secret 64)",
        "PC_BOOTSTRAP_TENANT=""$org""",
        "PC_BOOTSTRAP_ADMIN_EMAIL=$email",
        "PC_BOOTSTRAP_ADMIN_PASSWORD=$newPassword",
        "PC_LOAD_DEMO_COMPANY=$demoValue",
        'APP_PORT=8080',
        'WEB_CONCURRENCY=2'
    )
    # UTF-8 without a byte-order mark and Unix line endings, as docker compose expects
    [System.IO.File]::WriteAllText($envFile, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
}

# ------------------------------------------------------------------ build and start
Write-Host ''
Write-Host 'Building and starting - the first time takes 5 to 10 minutes...' -ForegroundColor Cyan
docker compose up -d --build
if ($LASTEXITCODE -ne 0) { Stop-WithMessage 'Starting failed - see the messages above.' }

$port = 8080
$portLine = Select-String -Path $envFile -Pattern '^APP_PORT=(\d+)' | Select-Object -First 1
if ($portLine) { $port = [int]$portLine.Matches[0].Groups[1].Value }
$url = "http://localhost:$port"

Write-Host 'Waiting for the application...' -ForegroundColor Cyan
$ready = $false
for ($i = 0; $i -lt 120; $i++) {
    try {
        $response = Invoke-WebRequest -Uri "$url/api/health" -UseBasicParsing -TimeoutSec 3
        if ($response.StatusCode -eq 200) { $ready = $true; break }
    } catch { }
    Start-Sleep -Seconds 2
}
if (-not $ready) { Stop-WithMessage "The application did not start. In this folder run:  docker compose logs app" }

# ------------------------------------------------------------------ summary
Write-Host ''
Write-Host "Product Costing is running: $url" -ForegroundColor Green
if ($newPassword) {
    Write-Host "Sign in as $email with the password:  $newPassword" -ForegroundColor Yellow
    Write-Host 'Change it after the first sign-in (Profile). It is also stored in the .env file.'
}
Write-Host "Colleagues on the same network: http://<this computer's IP address>:$port"
Write-Host 'Stop it:  docker compose stop      Start it again: run this script again.'
Start-Process $url
Read-Host 'Press Enter to close'
